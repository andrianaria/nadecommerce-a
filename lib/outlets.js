export function getOutletById(id) {
  return outlets.find((outlet) => outlet.id === id) || outlets[0];
}

export function findBestOutlet(address = "") {
  const haystack = String(address || "").toLowerCase();

  if (!haystack.trim()) {
    return outlets[0];
  }

  let bestOutlet = outlets[0];
  let bestScore = -1;

  for (const outlet of outlets) {
    const score = outlet.keywords.reduce((total, keyword) => {
      return total + (haystack.includes(keyword) ? 1 : 0);
    }, 0);

    if (score > bestScore) {
      bestOutlet = outlet;
      bestScore = score;
    }
  }

  return bestOutlet;
}

